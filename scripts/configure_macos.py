#!/usr/bin/env python3
"""Apply Tinglang branding, permissions and signing setup to a Flutter macOS runner.

No shell interpolation, no access to user documents, no credentials. Idempotent.

- App Sandbox off, Hardened Runtime on. Tinglang is AGPL and not shipped through
  the Mac App Store, and the Core Audio process tap is unverified in the sandbox.
- Outgoing network allowed (model downloads, YouTube, user-enabled cloud
  providers). The app itself only connects when the user turns a feature on.
- Literal NSAudioCaptureUsageDescription / NSMicrophoneUsageDescription in
  Info.plist (a missing audio-capture key makes the tap return silence), plus
  localised InfoPlist.strings for en and zh-Hans.
- Minimum macOS 14.2 (Core Audio process taps).
- Library validation disabled: media_kit embeds frameworks signed by another
  team, which Hardened Runtime would otherwise refuse to load.
- User-selected file access (read-write): file_picker checks this entitlement in
  the signature before it opens a file dialog, sandbox or not.
- Signing: ad-hoc by default; a developer's gitignored Local.xcconfig at the
  repository root (see Local.xcconfig.example) can set DEVELOPMENT_TEAM.
- The floating capture panel is the front door: the main window is hidden at
  launch (MainMenu.xib) and AppDelegate.swift keeps the app running when it
  is closed, reopens it from the Dock and adds caption controls to the Dock menu.
- `.tinglang` share files: an exported type (dev.eeeease.tinglang.package, a
  zip) and a document type Tinglang owns as a viewer, so Finder double-click,
  Open With and drops on the Dock icon open the app. The Swift plugin takes
  the files (FlutterAppDelegate forwards application(_:open:)) and keeps them
  until Dart asks. The document icon is drawn by macOS from the app icon.
- iCloud Drive sync (opt-in): a usage string for the iCloud Drive folder
  prompt. Tinglang has no iCloud container entitlement (no paid developer
  account); it writes a plain folder that macOS syncs.
"""
from pathlib import Path
import json
import plistlib
import re
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
DEPLOYMENT_TARGET = '14.2'

USAGE = {
    'en': {
        'NSMicrophoneUsageDescription':
            'TingLang records your speaking practice and, when you turn it on, live speech from '
            'the microphone. Audio stays on this Mac unless you enable a cloud service.',
        'NSAudioCaptureUsageDescription':
            'TingLang listens to audio playing on this Mac to show live captions. Audio stays on '
            'this Mac unless you enable a cloud service.',
        'NSFileProviderDomainUsageDescription':
            'When you turn on sync in Settings, TingLang keeps your courses, recordings and '
            'progress in a Tinglang folder in iCloud Drive so your other Macs get them too.',
    },
    'zh-Hans': {
        'NSMicrophoneUsageDescription':
            '听浪会录下你的口语练习；开启实时识别时也会使用麦克风。除非你主动开启云端服务，音频只保留在这台 Mac 上。',
        'NSAudioCaptureUsageDescription':
            '听浪会收听这台 Mac 正在播放的声音，用于显示实时字幕。除非你主动开启云端服务，音频只保留在这台 Mac 上。',
        'NSFileProviderDomainUsageDescription':
            '在设置中开启同步后，听浪会把课程、录音和学习进度保存在 iCloud 云盘的 Tinglang 文件夹里，你的其他 Mac 也能用上。',
    },
}

# The name people see: TingLang in English, 听浪 in Chinese (the bundle file
# stays Tinglang.app).
APP_NAME = {'en': 'TingLang', 'zh-Hans': '听浪'}

# `.tinglang` share files (lib/core/share_package.dart): a zip Tinglang owns.
PACKAGE_UTI = 'dev.eeeease.tinglang.package'
PACKAGE_EXTENSION = 'tinglang'
# Finder's "Kind"; InfoPlist.strings localises it by the English name.
PACKAGE_KIND = {'en': 'TingLang Package', 'zh-Hans': '听浪学习包'}

# Fixed object ids for the InfoPlist.strings variant group in project.pbxproj.
_BUILD_FILE = '5A7100000000000000000001'
_VARIANT = '5A7100000000000000000002'
_REFS = {'en': '5A7100000000000000000003', 'zh-Hans': '5A7100000000000000000004'}

APP_INFO = f'''// Generated by scripts/configure_macos.py. Edit the script, not this file.
PRODUCT_NAME = Tinglang
PRODUCT_BUNDLE_IDENTIFIER = dev.eeeease.tinglang
PRODUCT_COPYRIGHT = Copyright © 2026 eeeease and TingLang contributors. AGPL-3.0 or commercial licence.
MACOSX_DEPLOYMENT_TARGET = {DEPLOYMENT_TARGET}
ENABLE_HARDENED_RUNTIME = YES

// Ad-hoc ("Sign to Run Locally") unless Local.xcconfig provides a team.
CODE_SIGN_IDENTITY = -
DEVELOPMENT_TEAM =

// Optional, gitignored, per developer. See Local.xcconfig.example.
#include? "../../../Local.xcconfig"
'''


def _strings(values: dict) -> str:
    def quote(text: str) -> str:
        return text.replace('\\', '\\\\').replace('"', '\\"')
    lines = ['/* Generated by scripts/configure_macos.py */']
    lines += [f'"{key}" = "{quote(value)}";' for key, value in values.items()]
    return '\n'.join(lines) + '\n'


def _insert_once(text: str, marker: str, anchor: str, addition: str, before: bool = False) -> str:
    """Insert `addition` next to the first `anchor` unless `marker` already exists."""
    if marker in text:
        return text
    index = text.find(anchor)
    if index < 0:
        raise SystemExit(f'Unexpected Runner.xcodeproj layout: missing {anchor.strip()!r}. '
                         'Regenerate macos/ with scripts/bootstrap_macos.sh.')
    if not before:
        index += len(anchor)
    return text[:index] + addition + text[index:]


def register_infoplist_strings(pbxproj: str) -> str:
    """Add Runner/<lang>.lproj/InfoPlist.strings to the Runner target's resources."""
    text = pbxproj
    text = _insert_once(text, f'{_BUILD_FILE} /*', '/* Begin PBXBuildFile section */\n',
        f'\t\t{_BUILD_FILE} /* InfoPlist.strings in Resources */ = {{isa = PBXBuildFile; '
        f'fileRef = {_VARIANT} /* InfoPlist.strings */; }};\n')
    refs = ''.join(
        f'\t\t{ref} /* {lang} */ = {{isa = PBXFileReference; lastKnownFileType = text.plist.strings; '
        f'name = {lang}; path = {lang}.lproj/InfoPlist.strings; sourceTree = "<group>"; }};\n'
        for lang, ref in _REFS.items())
    text = _insert_once(text, f'{_REFS["en"]} /* en */ = ', '/* Begin PBXFileReference section */\n', refs)
    # Resources group (the one that lists MainMenu.xib as a child).
    text = _insert_once(text, f'{_VARIANT} /* InfoPlist.strings */,',
        '\t\t\t\t33CC10F42044A3C60003C045 /* MainMenu.xib */,\n',
        f'\t\t\t\t{_VARIANT} /* InfoPlist.strings */,\n')
    text = _insert_once(text, f'{_BUILD_FILE} /* InfoPlist.strings in Resources */,',
        '\t\t\t\t33CC10F62044A3C60003C045 /* MainMenu.xib in Resources */,\n',
        f'\t\t\t\t{_BUILD_FILE} /* InfoPlist.strings in Resources */,\n')
    children = ''.join(f'\t\t\t\t{ref} /* {lang} */,\n' for lang, ref in _REFS.items())
    text = _insert_once(text, f'{_VARIANT} /* InfoPlist.strings */ = {{', '/* End PBXVariantGroup section */',
        f'\t\t{_VARIANT} /* InfoPlist.strings */ = {{\n\t\t\tisa = PBXVariantGroup;\n'
        f'\t\t\tchildren = (\n{children}\t\t\t);\n\t\t\tname = InfoPlist.strings;\n'
        '\t\t\tpath = Runner;\n\t\t\tsourceTree = "<group>";\n\t\t};\n', before=True)
    text = _insert_once(text, '"zh-Hans",', 'knownRegions = (\n', '\t\t\t\t"zh-Hans",\n')
    return text


def declare_package_type(info: dict) -> None:
    """Exported UTI and document type for `.tinglang` files (idempotent).

    Viewer + Owner: Tinglang opens them (Finder double-click, Open With, a drop
    on the Dock icon) but does not edit them in place. The icon is generated by
    macOS from the app icon (CFBundleTypeIconSystemGenerated, macOS 11+), the
    way Apple's own Shortcuts and Notes declare theirs.
    """
    exported = [t for t in info.get('UTExportedTypeDeclarations', [])
                if t.get('UTTypeIdentifier') != PACKAGE_UTI]
    exported.append({
        'UTTypeIdentifier': PACKAGE_UTI,
        'UTTypeDescription': PACKAGE_KIND['en'],
        'UTTypeConformsTo': ['public.zip-archive', 'public.data'],
        'UTTypeTagSpecification': {'public.filename-extension': [PACKAGE_EXTENSION]},
        'UTTypeIcons': {},
    })
    info['UTExportedTypeDeclarations'] = exported
    documents = [d for d in info.get('CFBundleDocumentTypes', [])
                 if PACKAGE_UTI not in d.get('LSItemContentTypes', [])]
    documents.append({
        'CFBundleTypeName': PACKAGE_KIND['en'],
        'CFBundleTypeRole': 'Viewer',
        'LSHandlerRank': 'Owner',
        'LSItemContentTypes': [PACKAGE_UTI],
        'LSTypeIsPackage': False,
        'CFBundleTypeIconSystemGenerated': 1,
    })
    info['CFBundleDocumentTypes'] = documents


def hide_main_window_at_launch(xib: str) -> str:
    """Marks the MainFlutterWindow as not visible at launch (idempotent)."""
    match = re.search(r'<window [^>]*customClass="MainFlutterWindow"[^>]*>', xib)
    if match is None:
        raise SystemExit('Unexpected MainMenu.xib layout: no MainFlutterWindow. '
                         'Regenerate macos/ with scripts/bootstrap_macos.sh.')
    tag = match.group(0)
    if 'visibleAtLaunch=' in tag:
        new_tag = re.sub(r'visibleAtLaunch="[^"]*"', 'visibleAtLaunch="NO"', tag)
    else:
        new_tag = tag.replace('<window ', '<window visibleAtLaunch="NO" ', 1)
    return xib[:match.start()] + new_tag + xib[match.end():]


def configure(root: Path) -> None:
    runner = root / 'macos/Runner'
    info_path = runner / 'Info.plist'
    project = root / 'macos/Runner.xcodeproj/project.pbxproj'
    if not info_path.is_file() or not project.is_file():
        raise SystemExit('Missing Flutter macOS runner. Run scripts/bootstrap_macos.sh first.')
    with info_path.open('rb') as f:
        info = plistlib.load(f)
    info['CFBundleDisplayName'] = APP_NAME['en']
    info['CFBundleName'] = APP_NAME['en']
    info['CFBundleDevelopmentRegion'] = 'en'
    info['CFBundleLocalizations'] = list(USAGE)
    # Literal values (not build-setting references): the tap checks the key.
    info.update(USAGE['en'])
    declare_package_type(info)
    with info_path.open('wb') as f:
        plistlib.dump(info, f, sort_keys=False)
    for lang, values in USAGE.items():
        folder = runner / f'{lang}.lproj'
        folder.mkdir(exist_ok=True)
        names = {'CFBundleDisplayName': APP_NAME[lang], 'CFBundleName': APP_NAME[lang],
                 PACKAGE_KIND['en']: PACKAGE_KIND[lang]}
        (folder / 'InfoPlist.strings').write_text(_strings({**names, **values}), encoding='utf-8')
    for name in ['DebugProfile.entitlements', 'Release.entitlements']:
        path = runner / name
        if not path.is_file():
            raise SystemExit(f'Missing expected Flutter entitlements: {path}')
        with path.open('rb') as f:
            entitlements = plistlib.load(f)
        # Preserve Flutter's debug JIT and local debug server entitlements.
        entitlements['com.apple.security.app-sandbox'] = False
        # Hardened Runtime still gates the microphone behind this entitlement.
        entitlements['com.apple.security.device.audio-input'] = True
        entitlements['com.apple.security.network.client'] = True
        # media_kit's prebuilt frameworks (libmpv, ffmpeg…) are signed with the
        # vendor's Team ID; under Hardened Runtime an ad-hoc or own-team app
        # cannot map them otherwise (dyld: "different Team IDs"). Revisit when
        # Developer ID builds re-sign embedded frameworks (M9).
        entitlements['com.apple.security.cs.disable-library-validation'] = True
        # Without the sandbox these grant nothing extra, but file_picker reads
        # them from the signature before opening NSOpenPanel/NSSavePanel and
        # fails with ENTITLEMENT_NOT_FOUND when both are missing. Read-write
        # also covers save dialogs (exports).
        entitlements.pop('com.apple.security.files.user-selected.read-only', None)
        entitlements['com.apple.security.files.user-selected.read-write'] = True
        with path.open('wb') as f:
            plistlib.dump(entitlements, f, sort_keys=False)
    (runner / 'Configs/AppInfo.xcconfig').write_text(APP_INFO)
    text = re.sub(r'MACOSX_DEPLOYMENT_TARGET = [^;]+;',
        f'MACOSX_DEPLOYMENT_TARGET = {DEPLOYMENT_TARGET};', project.read_text())
    project.write_text(register_infoplist_strings(text))
    podfile = root / 'macos/Podfile'
    if podfile.exists():
        podfile.write_text(re.sub(r"platform :osx, '[^']+'",
            f"platform :osx, '{DEPLOYMENT_TARGET}'", podfile.read_text()))
    for name in ('MainFlutterWindow.swift', 'AppDelegate.swift'):
        shutil.copyfile(root / 'scripts/native' / name, runner / name)
    xib = runner / 'Base.lproj/MainMenu.xib'
    if not xib.is_file():
        raise SystemExit(f'Missing expected Flutter main menu: {xib}')
    xib.write_text(hide_main_window_at_launch(xib.read_text()))
    icons = runner / 'Assets.xcassets/AppIcon.appiconset'
    icons.mkdir(parents=True, exist_ok=True)
    images = []
    for size in (16, 32, 128, 256, 512):
        for scale in (1, 2):
            pixels = size * scale
            name = f'app_icon_{pixels}.png'
            shutil.copyfile(root / 'assets/brand' / name, icons / name)
            images.append(dict(size=f'{size}x{size}', idiom='mac', filename=name, scale=f'{scale}x'))
    (icons / 'Contents.json').write_text(json.dumps(dict(images=images,
        info=dict(version=1, author='tinglang')), indent=2) + '\n')
    signing = 'team from Local.xcconfig' if (root / 'Local.xcconfig').is_file() else 'ad-hoc'
    print(f'Configured Tinglang: macOS {DEPLOYMENT_TARGET}, Hardened Runtime, no sandbox, '
          f'network client, mic + system-audio usage strings (en, zh-Hans), '
          f'.{PACKAGE_EXTENSION} documents ({PACKAGE_UTI}), signing: {signing}.')


if __name__ == '__main__':
    configure(Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT)
