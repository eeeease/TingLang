#!/usr/bin/env python3
"""Turn the Tinglang mark SVGs into drawing code for the app and the panel.

Sources (the designer's final files, the single source of truth):
  assets/brand/svg/tinglang-mark.svg        + -dark.svg        (48 pt and up)
  assets/brand/svg/tinglang-mark-small.svg  + -small-dark.svg  (below 48 pt)

Each file is a filled wave (the thin, sharp start), a stroked path (the wave
thickening into a rounded "hi") and a dot, with one linear gradient in viewBox
coordinates. Light and dark files must share their geometry; only colours differ.

Outputs:
  lib/ui/brand_mark_geometry.dart   Flutter Path; arcs stay arcs (arcToPoint)
  packages/tinglang_native_macos/.../BrandMarkGeometry.swift
                                    SwiftUI Path; arcs become cubic Béziers

Usage: python3 tools/brand_mark_geometry.py [--check]
"""
from math import atan2, ceil, cos, hypot, pi, radians, sin, sqrt, tan
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SVG_DIR = ROOT / 'assets/brand/svg'
DART_OUT = ROOT / 'lib/ui/brand_mark_geometry.dart'
SWIFT_OUT = (ROOT / 'packages/tinglang_native_macos/macos/tinglang_native_macos/Sources'
             / 'tinglang_native_macos/BrandMarkGeometry.swift')
NS = {'svg': 'http://www.w3.org/2000/svg'}
VARIANTS = [('regular', 'tinglang-mark'), ('small', 'tinglang-mark-small')]
HEADER = 'Generated by tools/brand_mark_geometry.py from assets/brand/svg/. Do not edit.'


def numbers(text):
    return [float(v) for v in text.replace(',', ' ').split()]


def parse_path(d):
    """Absolute M/L/C/A/Z commands (all the mark uses) as (command, args) tuples."""
    tokens = re.findall(r'[A-Za-z]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?', d)
    arity = {'M': 2, 'L': 2, 'C': 6, 'A': 7, 'Z': 0}
    out, i, cmd = [], 0, None
    while i < len(tokens):
        if tokens[i].isalpha():
            cmd = tokens[i]
            i += 1
            if cmd not in arity:
                raise SystemExit(f'Unsupported path command {cmd!r} in {d!r}')
            if cmd == 'Z':
                out.append(('Z', ()))
                continue
        elif cmd is None or cmd == 'Z':
            raise SystemExit(f'Malformed path data: {d!r}')
        args = tuple(float(t) for t in tokens[i:i + arity[cmd]])
        if len(args) != arity[cmd]:
            raise SystemExit(f'Truncated {cmd} in {d!r}')
        out.append((cmd, args))
        i += arity[cmd]
        if cmd == 'M':
            cmd = 'L'  # Further coordinate pairs after M are line-tos.
    return out


def arc_to_cubics(x1, y1, rx, ry, phi_deg, large, sweep, x2, y2):
    """SVG endpoint arc → cubic Béziers of at most 90° each (SVG 2, appendix B.2)."""
    if (x1, y1) == (x2, y2):
        return []
    rx, ry = abs(rx), abs(ry)
    if rx == 0 or ry == 0:
        return [((x1, y1), (x2, y2), (x2, y2))]
    phi = radians(phi_deg)
    c, s = cos(phi), sin(phi)
    dx, dy = (x1 - x2) / 2, (y1 - y2) / 2
    x1p, y1p = c * dx + s * dy, -s * dx + c * dy
    scale = x1p ** 2 / rx ** 2 + y1p ** 2 / ry ** 2
    if scale > 1:
        rx, ry = rx * sqrt(scale), ry * sqrt(scale)
    num = rx * rx * ry * ry - rx * rx * y1p * y1p - ry * ry * x1p * x1p
    den = rx * rx * y1p * y1p + ry * ry * x1p * x1p
    k = sqrt(max(0.0, num / den))
    if large == sweep:
        k = -k
    cxp, cyp = k * rx * y1p / ry, -k * ry * x1p / rx
    cx = c * cxp - s * cyp + (x1 + x2) / 2
    cy = s * cxp + c * cyp + (y1 + y2) / 2

    def angle(ux, uy, vx, vy):
        return atan2(ux * vy - uy * vx, ux * vx + uy * vy)

    ux, uy = (x1p - cxp) / rx, (y1p - cyp) / ry
    vx, vy = (-x1p - cxp) / rx, (-y1p - cyp) / ry
    start = angle(1, 0, ux, uy)
    sweep_angle = angle(ux, uy, vx, vy)
    if not sweep and sweep_angle > 0:
        sweep_angle -= 2 * pi
    elif sweep and sweep_angle < 0:
        sweep_angle += 2 * pi
    count = max(1, ceil(abs(sweep_angle) / (pi / 2) - 1e-9))
    step = sweep_angle / count
    t = 4 / 3 * tan(step / 4)

    def point(x, y):
        return (c * rx * x - s * ry * y + cx, s * rx * x + c * ry * y + cy)

    segments = []
    for n in range(count):
        a, b = start + n * step, start + (n + 1) * step
        p1 = point(cos(a) - t * sin(a), sin(a) + t * cos(a))
        p2 = point(cos(b) + t * sin(b), sin(b) - t * cos(b))
        p3 = point(cos(b), sin(b))
        if rx == ry:
            # The curve's midpoint must stay on the circle.
            p0 = point(cos(a), sin(a))
            mx = (p0[0] + 3 * p1[0] + 3 * p2[0] + p3[0]) / 8
            my = (p0[1] + 3 * p1[1] + 3 * p2[1] + p3[1]) / 8
            assert abs(hypot(mx - cx, my - cy) - rx) < 1e-3 * max(1.0, rx), 'arc conversion drifted'
        segments.append((p1, p2, p3))
    segments[-1] = (segments[-1][0], segments[-1][1], (x2, y2))
    return segments


def load(name):
    root = ET.parse(SVG_DIR / f'{name}.svg').getroot()
    gradient = root.find('.//svg:linearGradient', NS)
    if gradient is None or gradient.get('gradientUnits') != 'userSpaceOnUse':
        raise SystemExit(f'{name}.svg: expected one userSpaceOnUse linearGradient')
    paths = root.findall('svg:path', NS)
    filled = [p for p in paths if p.get('fill', '').startswith('url(')]
    stroked = [p for p in paths if p.get('stroke', '').startswith('url(')]
    circles = root.findall('svg:circle', NS)
    if len(filled) != 1 or len(stroked) != 1 or len(circles) != 1 or len(paths) != 2:
        raise SystemExit(f'{name}.svg: expected one filled path, one stroked path and one circle')
    line = stroked[0]
    if (line.get('stroke-linecap'), line.get('stroke-linejoin')) != ('round', 'round'):
        raise SystemExit(f'{name}.svg: the stroked path must use round caps and joins')
    dot = circles[0]
    return {
        'viewBox': numbers(root.get('viewBox')),
        'gradient': [float(gradient.get(k)) for k in ('x1', 'y1', 'x2', 'y2')],
        'stops': [(float(s.get('offset')), s.get('stop-color').upper())
                  for s in gradient.findall('svg:stop', NS)],
        'wave': parse_path(filled[0].get('d')),
        'letters': parse_path(line.get('d')),
        'strokeWidth': float(line.get('stroke-width')),
        'dot': [float(dot.get(k)) for k in ('cx', 'cy', 'r')],
        'dotColor': dot.get('fill').upper(),
    }


def variants():
    out = []
    for key, base in VARIANTS:
        light, dark = load(base), load(f'{base}-dark')
        for field in ('viewBox', 'gradient', 'wave', 'letters', 'strokeWidth', 'dot'):
            if light[field] != dark[field]:
                raise SystemExit(f'{base}.svg and {base}-dark.svg differ in {field}')
        out.append((key, base, light, dark))
    return out


def fmt(value):
    text = f'{value:.4f}'.rstrip('0').rstrip('.')
    return '0' if text in ('-0', '') else text


def argb(hex_color):
    if not re.fullmatch(r'#[0-9A-F]{6}', hex_color):
        raise SystemExit(f'Unsupported colour {hex_color!r}')
    return f'0xFF{hex_color[1:]}'


def dart_path(commands):
    lines = ['Path()']
    for cmd, a in commands:
        if cmd == 'M':
            lines.append(f'  ..moveTo({fmt(a[0])}, {fmt(a[1])})')
        elif cmd == 'L':
            lines.append(f'  ..lineTo({fmt(a[0])}, {fmt(a[1])})')
        elif cmd == 'C':
            lines.append('  ..cubicTo(' + ', '.join(fmt(v) for v in a) + ')')
        elif cmd == 'A':
            rx, ry, rotation, large, sweep, x, y = a
            radius = (f'Radius.circular({fmt(rx)})' if rx == ry
                      else f'Radius.elliptical({fmt(rx)}, {fmt(ry)})')
            args = [f'Offset({fmt(x)}, {fmt(y)})', f'radius: {radius}']
            if rotation:
                args.append(f'rotation: {fmt(rotation)}')
            if large:
                args.append('largeArc: true')
            if not sweep:  # SVG sweep-flag 1 is clockwise in y-down coordinates.
                args.append('clockwise: false')
            lines.append('  ..arcToPoint(' + ', '.join(args) + ')')
        else:
            lines.append('  ..close()')
    return '\n'.join(lines)


def swift_path(commands):
    def pt(x, y):
        return f'CGPoint(x: {fmt(x)}, y: {fmt(y)})'

    lines, cur, start = ['Path { p in'], (0.0, 0.0), (0.0, 0.0)
    for cmd, a in commands:
        if cmd == 'M':
            lines.append(f'      p.move(to: {pt(*a)})')
            cur = start = a
        elif cmd == 'L':
            lines.append(f'      p.addLine(to: {pt(*a)})')
            cur = a
        elif cmd == 'C':
            lines.append(f'      p.addCurve(to: {pt(a[4], a[5])}, control1: {pt(a[0], a[1])}, '
                         f'control2: {pt(a[2], a[3])})')
            cur = (a[4], a[5])
        elif cmd == 'A':
            for c1, c2, end in arc_to_cubics(cur[0], cur[1], *a):
                lines.append(f'      p.addCurve(to: {pt(*end)}, control1: {pt(*c1)}, '
                             f'control2: {pt(*c2)})')
            cur = (a[5], a[6])
        else:
            lines.append('      p.closeSubpath()')
            cur = start
    lines.append('    }')
    return '\n'.join(lines)


def dart_source():
    out = [f'// {HEADER}', '// dart format off', "import 'dart:ui';", '',
           '/// Gradient stops and dot colour for one surface (light or dark).',
           'class BrandMarkColors {',
           '  const BrandMarkColors(this.stops, this.colors, this.dot);',
           '  final List<double> stops;', '  final List<Color> colors;', '  final Color dot;', '}', '',
           '/// One drawing of the Tinglang mark, in its SVG viewBox coordinates.',
           'class BrandMarkDrawing {',
           '  BrandMarkDrawing._(this.viewBox, this.gradientStart, this.gradientEnd, this.light, '
           'this.dark,', '      this.strokeWidth, this.wave, this.letters, this.dotCenter, '
           'this.dotRadius);',
           '  final Rect viewBox;', '  final Offset gradientStart;', '  final Offset gradientEnd;',
           '  /// Orange to ink with an ink dot, for paper.', '  final BrandMarkColors light;',
           '  /// Orange to paper with a paper dot, for dark surfaces.', '  final BrandMarkColors dark;',
           '  final double strokeWidth;', '  /// The thin, sharp start of the wave (filled).',
           '  final Path wave;',
           '  /// The wave thickening into "hi" (stroked with round caps and joins).',
           '  final Path letters;', '  final Offset dotCenter;', '  final double dotRadius;', '}']

    def colors(v):
        stops = ', '.join(fmt(o) for o, _ in v['stops'])
        cols = ', '.join(f'Color({argb(c)})' for _, c in v['stops'])
        return f'const BrandMarkColors([{stops}], [{cols}], Color({argb(v["dotColor"])}))'

    for key, base, light, dark in variants():
        x, y, w, h = light['viewBox']
        gx1, gy1, gx2, gy2 = light['gradient']
        cx, cy, r = light['dot']
        out += ['', f'/// {base}.svg and {base}-dark.svg.',
                f'final brandMark{key.capitalize()} = BrandMarkDrawing._(',
                f'  const Rect.fromLTWH({fmt(x)}, {fmt(y)}, {fmt(w)}, {fmt(h)}),',
                f'  const Offset({fmt(gx1)}, {fmt(gy1)}),', f'  const Offset({fmt(gx2)}, {fmt(gy2)}),',
                f'  {colors(light)},', f'  {colors(dark)},', f'  {fmt(light["strokeWidth"])},',
                '  ' + dart_path(light['wave']).replace('\n', '\n  ') + ',',
                '  ' + dart_path(light['letters']).replace('\n', '\n  ') + ',',
                f'  const Offset({fmt(cx)}, {fmt(cy)}),', f'  {fmt(r)},', ');']
    return '\n'.join(out) + '\n'


def swift_source():
    out = [f'// {HEADER}', 'import SwiftUI', '', 'extension BrandMark {',
           '  /// Gradient stops and dot colour for one surface (light or dark).',
           '  struct Colors {', '    let stops: [Gradient.Stop]', '    let dot: Color', '  }', '',
           '  /// One drawing of the Tinglang mark, in its SVG viewBox coordinates.',
           '  struct Drawing {', '    let viewBox: CGRect', '    let gradientStart: CGPoint',
           '    let gradientEnd: CGPoint', '    let light: Colors', '    let dark: Colors',
           '    let strokeWidth: CGFloat', '    /// The thin, sharp start of the wave (filled).',
           '    let wave: Path',
           '    /// The wave thickening into "hi" (stroked with round caps and joins).',
           '    let letters: Path', '    let dot: Path', '  }']

    def colors(v):
        stops = ', '.join(f'.init(color: Color(argb: {argb(c)}), location: {fmt(o)})'
                          for o, c in v['stops'])
        return f'Colors(\n      stops: [{stops}],\n      dot: Color(argb: {argb(v["dotColor"])}))'

    for key, base, light, dark in variants():
        x, y, w, h = light['viewBox']
        gx1, gy1, gx2, gy2 = light['gradient']
        cx, cy, r = light['dot']
        out += ['', f'  /// {base}.svg and {base}-dark.svg.', f'  static let {key} = Drawing(',
                f'    viewBox: CGRect(x: {fmt(x)}, y: {fmt(y)}, width: {fmt(w)}, height: {fmt(h)}),',
                f'    gradientStart: CGPoint(x: {fmt(gx1)}, y: {fmt(gy1)}),',
                f'    gradientEnd: CGPoint(x: {fmt(gx2)}, y: {fmt(gy2)}),',
                f'    light: {colors(light)},', f'    dark: {colors(dark)},',
                f'    strokeWidth: {fmt(light["strokeWidth"])},',
                f'    wave: {swift_path(light["wave"])},',
                f'    letters: {swift_path(light["letters"])},',
                f'    dot: Path(ellipseIn: CGRect(x: {fmt(cx - r)}, y: {fmt(cy - r)}, '
                f'width: {fmt(2 * r)}, height: {fmt(2 * r)})))']
    out.append('}')
    return '\n'.join(out) + '\n'


def main(argv):
    outputs = {DART_OUT: dart_source(), SWIFT_OUT: swift_source()}
    if '--check' in argv:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items()
                 if not p.is_file() or p.read_text() != text]
        if stale:
            raise SystemExit('Out of date (run python3 tools/brand_mark_geometry.py): '
                             + ', '.join(stale))
        print('Brand mark code matches assets/brand/svg.')
        return
    for path, text in outputs.items():
        path.write_text(text)
        print(f'Wrote {path.relative_to(ROOT)}')


if __name__ == '__main__':
    main(sys.argv[1:])
